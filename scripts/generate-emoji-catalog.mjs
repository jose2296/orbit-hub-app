/**
 * Generates the emoji catalogue the picker searches.
 *
 * Two packages, because neither has the whole thing: `emojilib` brings the
 * 1914 glyphs with their English keywords and no groups, and
 * `unicode-emoji-json` brings the groups and no keywords at all. A search over
 * exact names is not a search, which is why the first one is the source and
 * the second one only lends its groups.
 *
 * Both are devDependencies of the root: they are generation tools, not
 * runtime. The phone gets this file, which is committed like the output of
 * `generate-brand-assets.mjs` — a catalogue generated on every boot is a
 * catalogue missing somewhere.
 */

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const emojilib = require("emojilib/dist/emoji-en-US.json");
const byEmoji = require("unicode-emoji-json/data-by-emoji.json");

const entries = Object.entries(emojilib).map(([emoji, keywords]) => {
  const words = (keywords ?? []).map((word) => String(word).replace(/_/g, " ").toLowerCase());
  return {
    emoji,
    name: words[0] ?? emoji,
    keywords: words,
    group: byEmoji[emoji]?.group ?? "Other",
  };
});

entries.sort((a, b) => a.emoji.localeCompare(b.emoji));

const groups = [...new Set(entries.map((entry) => entry.group))].sort();

const out = [
  "/**",
  " * The emoji catalogue the picker searches.",
  " *",
  " * GENERATED by `scripts/generate-emoji-catalog.mjs` — do not edit by hand.",
  ` * ${entries.length} entries from emojilib, groups from unicode-emoji-json.`,
  " */",
  `export const EMOJI_GROUPS = ${JSON.stringify(groups)} as const;`,
  `export type EmojiGroup = (typeof EMOJI_GROUPS)[number];`,
  "",
  "export interface EmojiEntry {",
  "  emoji: string;",
  "  name: string;",
  "  keywords: readonly string[];",
  "  group: string;",
  "}",
  "",
  `export const EMOJI_CATALOG: readonly EmojiEntry[] = ${JSON.stringify(entries)};`,
  "",
].join("\n");

writeFileSync(
  new URL("../apps/mobile/src/lib/icons/emoji-catalog.generated.ts", import.meta.url),
  out,
);

console.log(`emoji catalogue: ${entries.length} entries, ${groups.length} groups`);
